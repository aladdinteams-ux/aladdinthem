#!/usr/bin/env python3
"""Step 2: turn the shared chrome (topbar/header/drawer/footer/mobile nav) into PHP template parts + per-language string tables.
Usage: python3 -I build/chrome.py SRC_DIR THEME_DIR"""
import sys, re, json, os, html
sys.path.insert(0, os.path.dirname(__file__))
from pagelib import *
src, theme = sys.argv[1:3]
pages = {(p['lang'], p['group']): p for p in list_pages(src)}

def chunks(h):
    b = h[h.index('<body'):]
    i = b.index('<main'); j = b.index('</main>') + 7
    k = b.index('<script', j)
    return b[b.index('>') + 1:i], b[j:k]

def normalise(c):
    c = re.sub(r' aria-current="(page|location)"', '', c)
    c = re.sub(r' class="current"', '', c)
    c = re.sub(r'(class="payab-uiverse-link) is-active"', r'\1"', c)
    c = re.sub(r'src="(?:\.\./)*assets/', 'src="{{ASSETS}}/', c)
    c = re.sub(r'<a class="sr-only"', '<a class="sr-only"', c)
    return c

parts = {}
for lang in LANGS:
    p = pages[(lang, '')]
    h = open(p['file'], encoding='utf8').read()
    pre, post = chunks(h)
    out = {}
    for name, c in (('pre', pre), ('post', post)):
        t, s = tokenise(normalise(c), p['path'])
        out[name] = (t, s)
    parts[lang] = out
for name in ('pre', 'post'):
    base_t = parts['fa'][name][0]
    for lang in ('en', 'ar'):
        assert parts[lang][name][0] == base_t, (name, lang, 'template differs')
        assert [k for k, _ in parts[lang][name][1]] == [k for k, _ in parts['fa'][name][1]]
print('templates identical across languages: OK')

def php(name):
    t, s = parts['fa'][name]
    t = t.replace('{{ASSETS}}', '<?php echo esc_url( $aladdin_assets ); ?>')
    t = t.replace('{{HOME}}', '<?php echo esc_url( $aladdin_search_action ); ?>')
    def rep(m):
        i = int(m.group(1)); kind = s[i][0]
        if kind == 't': return '<?php echo esc_html( $s[%d] ); ?>' % i
        if kind == 'a': return '<?php echo esc_attr( $s[%d] ); ?>' % i
        return '<?php echo esc_url( $s[%d] ); ?>' % i      # u / r (urls resolved in the string table)
    return re.sub(r'\{\{(\d+)\}\}', rep, t)

hdr = "<?php\n/** Generated by build/chrome.py from the approved HTML. Edit texts in Settings > Aladdin Payab, not here. */\ndefined( 'ABSPATH' ) || exit;\n/** @var array $s string table  @var string $aladdin_assets @var string $aladdin_search_action */\n?>"
tp = os.path.join(theme, 'template-parts'); os.makedirs(tp, exist_ok=True)
for name in ('pre', 'post'):
    open(os.path.join(tp, 'chrome-%s.php' % name), 'w', encoding='utf8').write(hdr + php(name))

# source leftovers: the en/ar mobile drawer label is Persian in the delivered HTML
FIX = {'en': {'ناوبری موبایل': 'Mobile navigation'}, 'ar': {'ناوبری موبایل': 'قائمة الجوال'}}
for lang, m in FIX.items():
    for name in ('pre', 'post'):
        parts[lang][name] = (parts[lang][name][0], [(k, m.get(v, v)) if k in ('t', 'a') else (k, v) for k, v in parts[lang][name][1]])

# string tables: per language, one list per part; urls stored as route keys 'lang:group' or raw
table = {}
for lang in LANGS:
    table[lang] = {}
    for name in ('pre', 'post'):
        rows = []
        for kind, val in parts[lang][name][1]:
            if kind == 'u': rows.append(['u', '%s:%s' % val])
            elif kind == 'r': rows.append(['r', val])
            else: rows.append([kind, html.unescape(val)])
        table[lang][name] = rows
os.makedirs(os.path.join(theme, 'inc/data'), exist_ok=True)
json.dump(table, open(os.path.join(theme, 'inc/data/chrome-strings.json'), 'w', encoding='utf8'), ensure_ascii=False, indent=0)
print({n: len(table['fa'][n]) for n in table['fa']})
